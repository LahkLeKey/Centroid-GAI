interface NativePoint {
    id: string;
    category: string;
    observations: string;
    vector: number[];
    description: string
}

interface NativeTable {
    points: NativePoint[];
    categories: string[];
    dimensions: number;
    releaseSha256: string;
    categoryMetadata?: {name: string; description : string}[]|undefined
}

const marker = '/* Curated static knowledge baseline; maintain these C sources directly. */';
const legacyMarker = '/* Generated by compile-native-knowledge.ts; do not edit by hand. */';
const {values} = parseArgs({
    options : {
        release : {type : 'string'},
        'source-c' : {type : 'string'},
        output : {type : 'string'},
        'top-per-category' : {type : 'string'}
    }
});
if ((!values.release && !values['source-c']) || (values.release && values['source-c']) ||
    !values.output)
    throw new Error(
        'Usage: --release <verified-release> | --source-c <table.c> --output <table.c> [--top-per-category <count>]');

function cString(value: string) {
    if (!/^[a-zA-Z0-9_:/.-]+$/.test(value))
        throw new Error(`Unsupported native identifier: ${value}`);
    return `"${value}"`;
}

function hasCompilerMarker(source: string) {
    return source.startsWith(marker) || source.startsWith(legacyMarker);
}

function loadRelease(directory: string): NativeTable {
    const verified = verifyCodebaseRelease(directory);
    const points = verified.index.points.map(point => ({
                                                 id : point.id,
                                                 category : point.category,
                                                 observations : point.observations,
                                                 vector : point.vector,
                                                 description : ''
                                             }));
    return {
        points,
        categories : [...new Set(points.map(point => point.category)) ].sort(compareIds),
        dimensions : verified.index.dimensions,
        releaseSha256 : sha256(readFileSync(resolve(directory, 'manifest.json')))
    };
}

/** Read generated C sources, including legacy monolithic tables and include fragments. */
function loadGeneratedC(path: string): NativeTable {
    const source = readFileSync(path, 'utf8');
    if (!hasCompilerMarker(source))
        throw new Error('Source C file is not generated by compile-native-knowledge.ts');
    const categoryBlock =
        source.match(/const char \*const cgai_static_knowledge_categories\[\] = \{([\s\S]*?)\n\};/);
    const rowBlock = source.match(
        /const cgai_static_knowledge_centroid cgai_static_knowledge_data\[\] = \{([\s\S]*?)\n\};/);
    const dimensions = source.match(
        /(?:cgai_knowledge_catalog_dimensions|cgai_static_knowledge_dimensions) = (\d+)U;/);
    const releaseSha = source.match(
        /(?:cgai_knowledge_catalog_release_sha256|cgai_static_knowledge_release_sha256_value)\[\] = "([a-f0-9]{64}|)";/);
    if (!dimensions || !releaseSha)
        throw new Error('Generated C table is missing required metadata');
    const categoryKeys = new Map<number, string>();
    const includes = [
        ...source.matchAll(
            /#include "(?:static_knowledge_data|knowledge_catalog)\/((?:category-\d+|\d+-[a-z0-9-]+)\.inc)"/g)
    ].map(match => match[1]!);
    const categorySources = [
        ...source.matchAll(
            /\/\* Category source: (?:static_knowledge_data|knowledge_catalog)\/(\d+-[a-z0-9-]+\.c) \*\//g)
    ].map(match => match[1]!);
    const files = categorySources.length ? categorySources : includes;
    const contents = files.map(name => {
        for (const directory of ['knowledge_catalog', 'static_knowledge_data']) {
            const candidate = resolve(dirname(path), directory, name);
            if (existsSync(candidate))
                return readFileSync(candidate, 'utf8');
        }
        throw new Error(`Missing generated knowledge category source: ${name}`);
    });
    const moduleMetadata = categoryBlock ? undefined : contents.map(text => {
        function field(name: string) {
            const match = text.match(new RegExp(`\\.${name} = "((?:[^"\\\\]|\\\\.)*)"`));
            if (!match)
                throw new Error(`Missing module metadata: ${name}`);
            return JSON.parse(`"${match[1]}"`) as string;
        }
        // Module metadata follows the private centroid array.
        const module = text.slice(text.indexOf('static const cgai_knowledge_module module'));
        text = module;
        return {key : field('key'), name : field('name'), description : field('description')};
    });
    const categoryLabels =
        categoryBlock ? [...categoryBlock[1]!.matchAll(/"([a-zA-Z0-9_:/.,&() -]+)"/g) ].map(
                            match => match[1]!)
                      : moduleMetadata!.map(item => item.name);
    if (!categoryLabels.length || categoryLabels.some(label => !label.trim()))
        throw new Error('Generated C table has invalid category labels');
    const rows = files.length ? contents.join('\n') : rowBlock?.[1] ?? '';
    if (!rowBlock && !files.length)
        throw new Error('Generated C table has no centroid rows or category sources');
    const points: NativePoint[] = [];
    const sharedBlock = source.match(
        /const float (?:cgai_knowledge_catalog_vectors|cgai_shared_knowledge_vectors)\[\]\[CGAI_STATIC_KNOWLEDGE_DIMENSIONS\] = \{([\s\S]*?)\n\};/);
    const sharedVectors =
        sharedBlock ? [...sharedBlock[1]!.matchAll(/\{([^{}]+)\}/g) ].map(match => match[1]!) : [];
    const rowPattern =
        /\{\s*(?:\.id\s*=\s*)?"([a-zA-Z0-9_:/.-]+)",\s*(?:\.category\s*=\s*)?(\d+)U,\s*(?:\.observations\s*=\s*)?UINT64_C\((\d+)\),\s*(?:(?:\.description\s*=\s*)?"((?:[^"\\]|\\.)*)",\s*)?(?:\.cluster\s*=\s*\d+U,\s*)?(?:\.vector\s*=\s*)?(?:(?:\(const float\[CGAI_STATIC_KNOWLEDGE_DIMENSIONS\]\))?\{([^{}]+)\}|(?:cgai_knowledge_catalog_vectors|cgai_shared_knowledge_vectors)\[\s*(\d+)\s*\])\s*\},?/g;
    for (const row of rows.matchAll(rowPattern)) {
        const categoryIndex = Number(row[2]);
        const category = moduleMetadata?.[categoryIndex]?.key ?? categoryKeyFromId(row[1]!);
        if (categoryIndex >= categoryLabels.length ||
            (categoryKeys.has(categoryIndex) && categoryKeys.get(categoryIndex) !== category))
            throw new Error(`Generated C table category mismatch: ${row[1]}`);
        categoryKeys.set(categoryIndex, category);
        const vectorText = row[5] ?? sharedVectors[Number(row[6])];
        if (!vectorText)
            throw new Error(`Missing shared vector: ${row[1]}`);
        // C baseline vectors use sparse designated initializers; omitted axes are zero.
        const literals = vectorText.replace(/\/\*[\s\S]*?\*\//g, '').split(',')
                             .map(value => value.trim()).filter(Boolean);
        const vector: number[] = [];
        let component = 0;
        for (const literal of literals) {
            const entry = literal.match(/^(?:\[\s*(\d+)\s*\]\s*=\s*)?([-+0-9.eE]+)F$/);
            if (!entry)
                throw new Error(`Invalid generated float literal: ${literal}`);
            if (entry[1] !== undefined)
                component = Number(entry[1]);
            if (component >= Number(dimensions[1]) || vector[component] !== undefined)
                throw new Error(`Invalid vector component: ${literal}`);
            vector[component++] = Number(entry[2]);
        }
        for (let component = 0; component < Number(dimensions[1]); ++component)
            vector[component] ??= 0;
        if (!category || vector.length !== Number(dimensions[1]) || !vector.every(Number.isFinite))
            throw new Error(`Invalid generated centroid row: ${row[1]}`);
        const description = row[4] === undefined ? '' : JSON.parse(`"${row[4]}"`) as string;
        points.push({id : row[1]!, category, observations : row[3]!, vector, description});
    }
    const count = source.match(
        /(?:cgai_knowledge_catalog_row_count|cgai_static_knowledge_data_count) = (\d+)U;/);
    if (!count || points.length !== Number(count[1]))
        throw new Error('Generated C table row count mismatch');
    const categories = categoryLabels.map((_, index) => {
        const key = categoryKeys.get(index);
        if (!key)
            throw new Error(`Generated C category ${index} has no centroid rows`);
        if (moduleMetadata && key !== moduleMetadata[index]!.key)
            throw new Error(`Generated C module key mismatch: ${index}`);
        return key;
    });
    const descriptionBlock = source.match(
        /const char \*const cgai_static_knowledge_category_descriptions\[\] = \{([\s\S]*?)\n\};/);
    const descriptions = descriptionBlock
                             ? [...descriptionBlock[1]!.matchAll(/"((?:[^"\\]|\\.)*)"/g) ].map(
                                   match => JSON.parse(`"${match[1]}"`) as string)
                             : moduleMetadata?.map(item => item.description);
    if (descriptions && descriptions.length !== categories.length)
        throw new Error('Generated C table category description count mismatch');
    points.sort((left, right) => compareIds(left.id, right.id));
    return {
        points,
        categories,
        dimensions : Number(dimensions[1]),
        releaseSha256 : releaseSha[1]!,
        categoryMetadata :
            descriptions
                ? categoryLabels.map((name, index) => ({name, description : descriptions[index]!}))
                : undefined
    };
}

function categoryKeyFromId(id: string) {
    // Maintained baseline IDs belong to a category, not an external model shard.
    const baseline = id.match(/^([a-z0-9/-]+):baseline-\d{3,}$/);
    if (baseline)
        return baseline[1]!;
    if (id.startsWith('encyclopedia:')) {
        const shard = id.slice('encyclopedia:'.length).split(':')[0]!;
        const cluster = shard.match(/^(cluster-\d+)-\d{4}$/)?.[1];
        if (!cluster)
            throw new Error(`Cannot recover encyclopedia category from ID: ${id}`);
        return `encyclopedia/${cluster}`;
    }
    const shard = id.split(':')[0]!;
    const category = shard.match(/^(.+)-\d{3}$/)?.[1];
    if (!category)
        throw new Error(`Cannot recover codebase category from ID: ${id}`);
    return category;
}

