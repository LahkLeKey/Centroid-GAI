function tokenExamples(items: {token: string; count : string}[]) {
    return items
        .filter(item => /^[a-z][a-z0-9'-]*$/i.test(item.token) &&
                        !commonTokens.has(item.token.toLowerCase()))
        .slice(0, 4)
        .map(item => `${item.token[0]!.toUpperCase()}${item.token.slice(1)} (${item.count})`);
}

function addEncyclopediaLabels(targets: Map<string, string[]>, topics: Map<string, string[]>) {
    const directory = resolve(repositoryRoot, 'knowledge/encyclopedia/simplewiki-v1');
    const sources = JSON.parse(readFileSync(resolve(directory, 'sources.json'), 'utf8')) as
                    {clusters : {id : string; title_terms : string[]}[]};
    const models =
        JSON.parse(readFileSync(resolve(directory, 'models.json'), 'utf8')) as
        {shards : {id : string; cluster : string; inspection : {path : string; sha256 : string}}[]};
    for (const cluster of sources.clusters) {
        const cues = cluster.title_terms.filter(term => !genericTopicTerms.has(term.toLowerCase()));
        topics.set(cluster.id, cues.slice(0, 6));
    }
    for (const shard of models.shards) {
        const bytes = readFileSync(resolve(directory, shard.inspection.path));
        if (sha256(bytes) !== shard.inspection.sha256)
            throw new Error(`Encyclopedia inspection checksum mismatch: ${shard.id}`);
        const inspection =
            JSON.parse(bytes.toString('utf8')) as
            {centroids : {id : number; tokens : {items : {token : string; count : string}[]}}[]};
        for (const centroid of inspection.centroids) {
            const id = `encyclopedia:${shard.id}:${String(centroid.id).padStart(4, '0')}`;
            targets.set(id, tokenExamples(centroid.tokens.items));
        }
    }
}

function addCodebaseLabels(targets: Map<string, string[]>) {
    const directory = resolve(repositoryRoot, 'knowledge/codebase/codebase-v1');
    const manifestPath = resolve(directory, 'manifest.json');
    if (!existsSync(manifestPath))
        return;
    const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as {
        files: {path: string; sha256 : string}[];
        shards: {id: string; model : string; centroids : number}[]
    };
    for (const shard of manifest.shards) {
        const compressed = readFileSync(resolve(directory, shard.model));
        const expected = manifest.files.find(file => file.path === shard.model);
        if (!expected || sha256(compressed) !== expected.sha256)
            throw new Error(`Codebase model checksum mismatch: ${shard.id}`);
        const payload = gunzipSync(compressed, {maxOutputLength : 64 * 1024 * 1024});
        for (let centroid = 0; centroid < shard.centroids; centroid++) {
            const detail = inspectNativeContents(payload, 'centroid', 0, 12, centroid);
            targets.set(`${shard.id}:${String(centroid).padStart(4, '0')}`,
                        tokenExamples(detail.tokens.items));
        }
    }
}

